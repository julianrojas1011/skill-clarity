def save_report(path: Path, content: str, scan: dict[str, Any], inputs: list[Path]) -> None:
    path = path.expanduser().absolute()
    if path.is_symlink():
        raise ValueError("Output must not be a symlink")
    target = path.resolve()
    if target in {p.resolve() for p in inputs}:
        raise ValueError("Output must not overwrite an input")
    for root in scan["scan_context"]["roots"] + scan["scan_context"].get("candidates", []):
        boundary = Path(root).resolve()
        if boundary.is_file():
            boundary = boundary.parent
        if is_within(target, boundary):
            raise ValueError("Output must be outside inspected sources")
    if target.exists():
        if not target.is_file() or target.stat().st_size > MAX_JSON_BYTES:
            raise ValueError("Output exists and is not a generated report")
        with target.open(encoding="utf-8") as handle:
            start = handle.read(256)
        if MARKER not in start:
            raise ValueError("Refusing to overwrite an unrelated file")
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".clarity-", dir=target.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, target)
    except BaseException:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("validate", "render"):
        command = sub.add_parser(name)
        command.add_argument("--scan", required=True, type=Path)
        command.add_argument("--review", required=name == "validate", type=Path)
        command.add_argument("--environment", help="Optional exact declaration to detect a changed review context; not host telemetry.")
        if name == "render":
            command.add_argument("--format", choices=("html", "markdown"), default="html")
            command.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        scan = read_json(args.scan, "scan")
        review = read_json(args.review, "review") if args.review else None
        result = validate(scan, review, args.environment) if review else None
        if args.command == "validate":
            print(json.dumps(result, ensure_ascii=False, indent=2))
        else:
            if review and any(f["status"] == "invalid" for f in result["findings"]):
                raise ValueError("Review contains invalid findings; run validate and correct source attribution before rendering")
            save_report(args.output, render(scan, review, result, args.format), scan,
                        [args.scan] + ([args.review] if args.review else []))
            print(json.dumps({"output": str(args.output.resolve()), "evidence_current": result["valid"] if result else False}))
        return 0 if result is None or result["valid"] else 1
    except (OSError, ValueError, ScanError, KeyError, TypeError, RuntimeError) as exc:
        print(json.dumps({"tool": "skill-clarity", "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
